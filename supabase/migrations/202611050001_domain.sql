-- Demo schema. Contract cardinalities below are implementation assumptions, not production approvals.
create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated, anon;

create table public.clients (
 id bigint generated by default as identity primary key,
 name text not null check (length(trim(name)) between 1 and 100),
 email text not null check (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
 created_at timestamptz not null default now()
);
create table public.accounts (
 id uuid primary key references auth.users(id) on delete restrict,
 role text not null check (role in ('admin','buyer')),
 enabled boolean not null default false
);
create table public.account_clients (
 account_id uuid not null references public.accounts(id) on delete restrict,
 client_id bigint not null references public.clients(id) on delete restrict,
 primary key (account_id,client_id)
);
create index account_clients_client_idx on public.account_clients(client_id);
create table public.properties (
 id text primary key check (id ~ '^[a-z0-9-]+$'),
 title text not null check (length(trim(title)) between 1 and 150),
 subtitle text not null default '', description text not null,
 operation text not null check (operation in ('Venta','Alquiler')),
 published boolean not null default false,
 created_at timestamptz not null default now()
);
create index properties_published_idx on public.properties(published);
create table public.property_photos (
 id uuid primary key default gen_random_uuid(),
 property_id text not null references public.properties(id) on delete restrict,
 object_path text unique, reference_url text,
 position integer not null default 0 check(position>=0),
 alt text not null,
 check ((object_path is null) <> (reference_url is null)),
 check(reference_url is null or reference_url like 'https://images.unsplash.com/%')
);
create index photos_property_idx on public.property_photos(property_id);
create table public.lots (
 id text primary key, property_id text not null references public.properties(id),
 area numeric(12,2) check(area>0), block text,
 demo_state text not null check(demo_state in ('Disponible','Adjudicado'))
);
create table public.contracts (
 id bigint generated by default as identity primary key,
 reference text not null unique, signed_on date not null,
 currency text not null check(currency='USD'),
 total numeric(14,2) not null check(total>0),
 deposit numeric(14,2) not null check(deposit>=0 and deposit<=total),
 demo_scenario boolean not null default true check(demo_scenario)
);
create table public.contract_clients (
 contract_id bigint not null references public.contracts(id),
 client_id bigint not null references public.clients(id), primary key(contract_id,client_id)
);
create index contract_clients_client_idx on public.contract_clients(client_id);
create table public.contract_lots (
 contract_id bigint not null references public.contracts(id),
 lot_id text not null references public.lots(id), primary key(contract_id,lot_id)
);
create index contract_lots_lot_idx on public.contract_lots(lot_id);
create table public.plans (
 id bigint generated by default as identity primary key,
 contract_id bigint not null references public.contracts(id),
 label text not null,
 created_at timestamptz not null default now()
);
create index plans_contract_idx on public.plans(contract_id);
create table public.installments (
 id bigint generated by default as identity primary key,
 plan_id bigint not null references public.plans(id),
 number integer not null check(number>0),
 due_on date not null, amount numeric(14,2) not null check(amount>0),
 demo_state text not null default 'Pendiente' check(demo_state in ('Pendiente','Al día','A vencer','Vencidas')),
 unique(plan_id,number)
);
create table public.payments (
 id bigint generated by default as identity primary key,
 contract_id bigint not null references public.contracts(id),
 amount numeric(14,2) not null check(amount>0),
 paid_on date not null,
 method text not null check(method in ('Transferencia','Efectivo')),
 actor uuid not null references auth.users(id),
 request_id uuid not null unique,
 voided boolean not null default false,
 created_at timestamptz not null default now()
);
create index payments_contract_idx on public.payments(contract_id);
create table public.payment_allocations (
 payment_id bigint not null references public.payments(id),
 installment_id bigint not null references public.installments(id),
 amount numeric(14,2) not null check(amount>0), primary key(payment_id,installment_id)
);
create index allocations_installment_idx on public.payment_allocations(installment_id);
create table public.payment_events (
 id uuid primary key default gen_random_uuid(),
 payment_id bigint not null references public.payments(id),
 operation text not null check(operation in ('registered','voided')),
 before_value jsonb, after_value jsonb not null,
 reason text not null check(length(trim(reason))>=5),
 actor uuid not null references auth.users(id),
 request_id uuid not null unique,
 created_at timestamptz not null default now()
);
create index events_payment_idx on public.payment_events(payment_id);
create table public.receipts (
 id uuid primary key default gen_random_uuid(), payment_id bigint not null references public.payments(id),
 object_path text not null unique, mime_type text not null check(mime_type in ('application/pdf','image/png','image/jpeg')),
 created_at timestamptz not null default now()
);
create index receipts_payment_idx on public.receipts(payment_id);

create function private.is_admin() returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.accounts where id=auth.uid() and role='admin' and enabled)
$$;
create function private.can_client(target bigint) returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.accounts a join public.account_clients ac on ac.account_id=a.id
 where a.id=auth.uid() and a.enabled and ac.client_id=target)
$$;
create function private.can_contract(target bigint) returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.contract_clients cc where cc.contract_id=target and private.can_client(cc.client_id))
$$;
create function private.can_payment(target bigint) returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.payments p where p.id=target and private.can_contract(p.contract_id))
$$;
revoke all on all functions in schema private from public;
grant execute on all functions in schema private to authenticated, anon;

do $$ declare t text; begin
 foreach t in array array['clients','accounts','account_clients','properties','property_photos','lots','contracts','contract_clients','contract_lots','plans','installments','payments','payment_allocations','payment_events','receipts'] loop
  execute format('alter table public.%I enable row level security',t);
  execute format('revoke all on public.%I from anon, authenticated',t);
  execute format('grant select on public.%I to authenticated',t);
  execute format('create policy admin_read on public.%I for select to authenticated using (private.is_admin())',t);
 end loop;
end $$;
grant select on public.properties, public.property_photos to anon;
create policy public_properties on public.properties for select to anon,authenticated using(published);
create policy public_photos on public.property_photos for select to anon,authenticated using(exists(select 1 from public.properties p where p.id=property_id and p.published));
grant insert,update on public.properties,public.property_photos to authenticated;
create policy properties_insert on public.properties for insert to authenticated with check(private.is_admin());
create policy properties_update on public.properties for update to authenticated using(private.is_admin()) with check(private.is_admin());
create policy photos_insert on public.property_photos for insert to authenticated with check(private.is_admin());
create policy photos_update on public.property_photos for update to authenticated using(private.is_admin()) with check(private.is_admin());
grant insert on public.clients to authenticated;
grant usage on sequence public.clients_id_seq to authenticated;
create policy clients_insert on public.clients for insert to authenticated with check(private.is_admin());
create policy buyer_clients on public.clients for select to authenticated using(private.can_client(id));
create policy own_account on public.accounts for select to authenticated using(id=auth.uid());
create policy own_links on public.account_clients for select to authenticated using(account_id=auth.uid());
create policy buyer_contracts on public.contracts for select to authenticated using(private.can_contract(id));
create policy buyer_contract_clients on public.contract_clients for select to authenticated using(private.can_contract(contract_id));
create policy buyer_contract_lots on public.contract_lots for select to authenticated using(private.can_contract(contract_id));
create policy buyer_lots on public.lots for select to authenticated using(exists(select 1 from public.contract_lots cl where cl.lot_id=id and private.can_contract(cl.contract_id)));
create policy buyer_plans on public.plans for select to authenticated using(private.can_contract(contract_id));
create policy buyer_installments on public.installments for select to authenticated using(exists(select 1 from public.plans p where p.id=plan_id and private.can_contract(p.contract_id)));
create policy buyer_payments on public.payments for select to authenticated using(private.can_contract(contract_id));
create policy buyer_allocations on public.payment_allocations for select to authenticated using(private.can_payment(payment_id));
-- Event history includes internal reasons: administrators only. Buyers see the current payment state.
create policy buyer_receipts on public.receipts for select to authenticated using(private.can_payment(payment_id));

create function private.immutable_history() returns trigger language plpgsql set search_path='' as $$
begin raise exception 'Historical records are immutable' using errcode='42501'; end $$;
create trigger events_immutable before update or delete on public.payment_events for each row execute function private.immutable_history();
create trigger allocations_immutable before update or delete on public.payment_allocations for each row execute function private.immutable_history();
create function private.protect_payment() returns trigger language plpgsql set search_path='' as $$
begin
 if tg_op='DELETE' then raise exception 'Payments cannot be deleted' using errcode='42501'; end if;
 if (to_jsonb(new)-'voided') is distinct from (to_jsonb(old)-'voided') then raise exception 'Original payment is immutable' using errcode='42501'; end if;
 return new;
end $$;
create trigger protect_payment before update or delete on public.payments for each row execute function private.protect_payment();
